                            <p>Powdered latex examination gloves are disposable gloves used by healthcare professionals in a medical and laboratory setup. They are mainly made of latex, nitrile, neoprene and a mix of various synthetic rubber materials. These gloves are designed to provide a protective barrier between the wearer and infected microorganisms, bodily fluids, and chemicals. The term “powdered” refers to the presence of a fine powder such as biodegradable cornstarch applied to the glove. Some of its benefits are:</p>
                            <ul>
                                <li>Easy donning – The powder helps in the reduction of friction between the gloves and the hands, making it easier to put on and remove.</li>
                                <li>Better moisture absorption – The powder helps in easier absorption of moisture which gets accumulated after prolonged use, making it difficult to use.</li>
                                <li>Better grip – The powder improves grip and dexterity, making it easier to handle anything with full confidence.
                                </li>
                            </ul>
                            <p style="margin-top:15px">One important thing to note is that powdered gloves have certain health risks which can cause irritation or unwanted reactions in patients who are prone to allergies or suffer from asthma. It is upto the medical caregivers to consider the patient's medical history before they use the surgical gloves to minimise the chances of an allergic reaction while maintaining complete functionality</p>
