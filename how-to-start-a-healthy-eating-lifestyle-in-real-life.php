                            <p>We get it, eating healthy isn’t as easy it seems at times. Don’t get us wrong, the problem isn’t with “eating healthy” but with convincing ourselves to eat healthy after years of being spent binging on oily, greasy food items that’s one bite away from a heart attack. Human beings are creatures of habit, especially the bad ones – no wonder we can’t just leave our greasy burgers and oily aloo paratha even if it’s a matter of our health. There is a reason why India has one of the highest cases of heart-related diseases in the world. Bad food habits, unhealthy lifestyle, and unwillingness to give up on it just because it’s their comfort zone. No matter – we do have a few hacks to get you started with without even putting any conscious effort into it. You will move on to a healthier routine and begin to crave “healthy eating” before you even realise it. Here we go.</p>
                            <br>
                            <ul class="ul_list" style="padding-left:20px;">
                                <li>Start your day with a warm glass of water. Drinking water gets your cells activated and hydrated. Keep a bottle beside your bed. This helps you to remind yourself to drink more water. Adults need to drink upto 3-4 litres of water a day. Try maintaining that.</li>
                                <li>Prepare your meal in advance. If you are always in a hurry during the mornings and tend to skip your breakfast. It’s a good idea to prepare your meal at night. All you have to do in the morning is quickly reheat it and pack it. Also, keeping small packs of energy bars and an apple handy with you while at work always helps.</li>
                                <li>Keep a track of what you eat. Prepare a chart or a note for the food items you have eaten during the week or what you plan to eat in the coming week and stick to it. If you can’t follow the entire plant, at least try to meet 70-80% of the commitment and try improving on it as you go.</li>
                                <li>Eat 4-5 times a day. The more you eat in smaller quantities, the less you feel hungry and less urge to eat junk food items. Carry small snacks like apples, candy bars, peanuts, and cashews with you to work. Pop them whenever hunger strikes. This will reduce your dependency on junk food and eating a whole lot of food in one sitting.</li>
                                <li>Get someone to work with you. The way to the top is always a lonely journey. Get someone to tag along with you. It’s a proven fact that we are more productive when we work in a group. The simple reason for that is our base instinct to prove ourselves. A little competition can go a long way in this case. Grab hold of your spouse, mom, dad or anyone else in your neighbourhood.</li>
                                <li>Take inspiration. It’s a good idea to find some form of inspiration from individuals who might have gone through a similar challenge as yours. This allows you to relate to their struggles, challenges and their victories. Follow their story to find what works and what doesn’t and try applying it on your end and see where that takes you.</li>
                                <li>Focus on the little things. The process of getting someone to leave an unhealthy lifestyle is similar to drug withdrawal symptoms which could be more damaging in certain cases. As a result, it is imperative to focus on the small things and build upon them. Go for a walk, reduce your junk food intake gradually, drink fruit juice instead of soda-based drinks, eat the greens you like and try experimenting with your food.</li>
                            </ul>
