                            <p style="margin-top:15px">The surgical gloves were invented around the 1900s in the USA by William Stewart Halsted. He was also credited with developing a plethora of operating procedures and training programs that became the benchmark for becoming a quality surgeon during his time. In the current scheme of things, <a href="index.php">surgical gloves</a> are an integral part of the medical fraternity and are used for both medical and non-medical purposes to improve the safety standards of the medical institution. However, this wasn’t the case a hundred years back when surgeons used their bare hands to operate on patients and continued to do so for many more years before its importance was established.</p>
                            <h3>So, Why Are Surgical Gloves So Important For Surgeons?</h3>
                            <p style="margin-top:15px">Until the 1930s-40s, doctors dipped their hands in disinfectants before they operated on patients with their bare hands. Continued use of disinfectant led to various health complications that affected their hands over time. Additionally, the bare hands could contract microorganisms and pathogens while also infecting the patient while conducting the procedure. All of this combined led to a collective decision among medical institutions across the globe to incorporate the use of surgical gloves in all medical procedures; big or small.</p>
                            <p style="margin-top:15px">The purpose of a surgical glove is simple; to create a barrier which protects the health professional from chemicals, disease-causing microbes, and pathogens among others. On the other hand, it also protects patients from the same health hazards while undergoing any surgery or medical procedure. Given the impact this issue can have on the stakeholders, it is of utmost importance to ensure medical institutions procure high-quality surgical gloves that can endure the rigours of the work while delivering optimal performance. After all, the final objective of any medical institution across the globe is the same; To save lives however we can!</p>
