                            <p>Examination gloves are commonly used by medical professionals across the globe for performing medical procedures and examining patients. The primary function of examination gloves is to protect the user from cross-contamination when handling a patient or potentially infectious or contaminated material. Examination gloves become a protective layer for the user that ensures that the skin doesn’t get exposed to the disease-causing micro-organism. Imagine working with paint – if you get paint on the gloves you are wearing, all you have to do is remove the gloves and your hands remain unaffected by it. The same principle applies in a medical scenario too.</p>
