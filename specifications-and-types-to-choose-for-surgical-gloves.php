                            <p>Granted, most medical or surgical gloves do look the same in the first instance. However, it couldn’t be further from the truth. While the general shape and feel of all medical gloves are fundamentally the same; it is made to fit human hands and it is usually made of natural, synthetic latex or a combination of both. Nevertheless, the similarity ends there; there are several variants of surgical gloves available to health professionals which are used according to the specific task to be undertaken. Surgical gloves are usually sized more precisely since they are worn for a much longer period and require exceptional dexterity. The sizing of surgical gloves are based on the measured circumference around the palm (excluding the thumb) in inches, at a level slightly above the thumb's sewn. Typical sizing ranges from 5.5 to 9.0 at an increment of 0.5. In case of an invasive procedure or an elaborate surgery, the gloves used are usually thicker and focus more on durability and puncture resistance. There are other cases that also arise out of allergic reactions of patients, the shelf-life of the gloves, and other technicalities of the field of work. Hence, the task essentially dictates the type of gloves to be donned to ensure the safety of the patient and the health professional. Based on consensus, there are primarily four types of surgical gloves currently available in the market.</p>
                            <ul style="margin-top:15px;">
                                <li>Surgical Pre-Powdered Gloves</li>
